export function generateRobotsTxt(siteUrl: string, isSiteWideNoIndex?: boolean): string {
  const normalizedSiteUrl = siteUrl.replace(/\/+$/, '');
  if (isSiteWideNoIndex) {
    return `# Robots.txt generated by Planfo Static CMS
# Search engine indexing is discouraged for this site
User-agent: *
Disallow: /
`;
  }

  return `# Robots.txt generated by Planfo Static CMS
User-agent: *
Allow: /

Sitemap: ${normalizedSiteUrl}/sitemap.xml
`;
}
